import type { HandwritingScript } from '../types';

export const INITIALS = ['ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ', 'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'];
export const VOWELS = ['ㅏ', 'ㅐ', 'ㅑ', 'ㅒ', 'ㅓ', 'ㅔ', 'ㅕ', 'ㅖ', 'ㅗ', 'ㅘ', 'ㅙ', 'ㅚ', 'ㅛ', 'ㅜ', 'ㅝ', 'ㅞ', 'ㅟ', 'ㅠ', 'ㅡ', 'ㅢ', 'ㅣ'];
export const FINALS = ['', 'ㄱ', 'ㄲ', 'ㄳ', 'ㄴ', 'ㄵ', 'ㄶ', 'ㄷ', 'ㄹ', 'ㄺ', 'ㄻ', 'ㄼ', 'ㄽ', 'ㄾ', 'ㄿ', 'ㅀ', 'ㅁ', 'ㅂ', 'ㅄ', 'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'];

export const RUSSIAN_ALPHABET = [
    'а', 'б', 'в', 'г', 'д', 'е', 'ё', 'ж', 'з', 'и', 'й', 'к', 'л', 'м', 'н', 'о',
    'п', 'р', 'с', 'т', 'у', 'ф', 'х', 'ц', 'ч', 'ш', 'щ', 'ъ', 'ы', 'ь', 'э', 'ю', 'я'
];

export const UKRAINIAN_ALPHABET = [
    'а', 'б', 'в', 'г', 'ґ', 'д', 'е', 'є', 'ж', 'з', 'и', 'і', 'ї', 'й', 'к', 'л', 'м',
    'н', 'о', 'п', 'р', 'с', 'т', 'у', 'ф', 'х', 'ц', 'ч', 'ш', 'щ', 'ь', 'ю', 'я'
];

export function scriptForLanguage(language: string): HandwritingScript {
    const normalized = language.trim().toLowerCase();
    if (normalized.includes('russian')) return 'russian';
    if (normalized.includes('ukrainian')) return 'ukrainian';
    return 'korean';
}

export function supportsWordBuilding(language: string): boolean {
    const normalized = language.trim().toLowerCase();
    return !normalized || ['korean', 'russian', 'ukrainian'].some(name => normalized.includes(name));
}

export function composeHangul(initial: string | null, vowel: string | null, final: string | null): string {
    if (!initial) return '';
    const initialIndex = INITIALS.indexOf(initial);
    const vowelIndex = vowel ? VOWELS.indexOf(vowel) : -1;
    const finalIndex = final ? FINALS.indexOf(final) : -1;
    if (initialIndex === -1 || vowelIndex === -1) return initial + (vowel || '') + (final || '');
    return String.fromCharCode(44032 + initialIndex * 588 + vowelIndex * 28 + Math.max(0, finalIndex));
}
